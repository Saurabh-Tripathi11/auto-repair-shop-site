/**
 * Static build. Every tenant renders to one HTML file plus their own assets.
 *
 *   dist/
 *     routes.json          host -> tenant, for whatever is doing the routing
 *     Caddyfile            ready-to-run reverse proxy with automatic TLS
 *     index.html           local directory of tenants (not deployed per-tenant)
 *     <slug>/index.html    the tenant's site
 *     <slug>/...           the tenant's public/ assets
 */

import { mkdir, writeFile, rm, cp } from 'node:fs/promises';
import path from 'node:path';

import { FileTenantStore } from './core/tenant.js';
import { renderPage } from './core/render.js';
import { defaultRegistry } from './sections/index.js';
import { esc } from './core/html.js';

export function createStore(root) {
  return new FileTenantStore(path.join(root, 'tenants'), { baseRegistry: defaultRegistry() });
}

async function writeTenant(tenant, outDir, { now }) {
  const { html, warnings } = renderPage(tenant, { now });
  const dir = path.join(outDir, tenant.slug);
  await mkdir(dir, { recursive: true });
  await writeFile(path.join(dir, 'index.html'), html, 'utf8');

  if (tenant.publicDir) {
    await cp(tenant.publicDir, dir, { recursive: true });
  }

  const canonical = tenant.config.seo.canonical;
  const noindex = tenant.config.seo.noindex;
  await writeFile(
    path.join(dir, 'robots.txt'),
    noindex
      ? 'User-agent: *\nDisallow: /\n'
      : `User-agent: *\nAllow: /\n${canonical ? `Sitemap: ${canonical.replace(/\/$/, '')}/sitemap.xml\n` : ''}`,
    'utf8'
  );

  if (canonical && !noindex) {
    await writeFile(
      path.join(dir, 'sitemap.xml'),
      `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>${canonical}</loc></url>\n</urlset>\n`,
      'utf8'
    );
  }

  return { slug: tenant.slug, bytes: Buffer.byteLength(html), warnings };
}

function routesFor(tenants) {
  const routes = {};
  for (const tenant of tenants) {
    for (const domain of tenant.config.domains) routes[String(domain).toLowerCase()] = tenant.slug;
  }
  return routes;
}

function caddyfile(tenants) {
  const blocks = tenants
    .filter((t) => t.config.domains.length)
    .map((t) => `${t.config.domains.join(', ')} {\n\troot * /srv/${t.slug}\n\tfile_server\n\tencode gzip zstd\n}`);
  return `# Generated by shopfront build. Custom domains with automatic TLS.\n# Point each domain's A/AAAA record at this host, then: caddy run\n\n${blocks.join('\n\n')}\n`;
}

function directoryPage(results, tenants) {
  const rows = tenants.map((t) => {
    const result = results.find((r) => r.slug === t.slug);
    const domains = t.config.domains.length ? t.config.domains.map(esc).join(', ') : '<em>no domain configured</em>';
    return `    <tr><td><a href="./${esc(t.slug)}/index.html">${esc(t.config.business.name)}</a></td>` +
      `<td>${esc(t.slug)}</td><td>${domains}</td><td>${(result.bytes / 1024).toFixed(1)} KB</td></tr>`;
  });

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>shopfront — tenants</title>
<style>
  body { font: 15px/1.5 system-ui, sans-serif; margin: 0; padding: 40px 20px; color: #1c2229; }
  main { max-width: 760px; margin: 0 auto; }
  h1 { font-size: 22px; margin: 0 0 4px; }
  p { color: #5c6874; margin: 0 0 24px; }
  table { border-collapse: collapse; width: 100%; }
  th, td { text-align: left; padding: 9px 10px; border-bottom: 1px solid #dbe1e8; }
  th { font-size: 12px; text-transform: uppercase; letter-spacing: 0.08em; color: #5c6874; }
  em { color: #79838f; }
</style>
</head>
<body>
<main>
  <h1>Tenants</h1>
  <p>Build output preview. Each tenant deploys as its own static root.</p>
  <table>
    <thead><tr><th>Shop</th><th>Slug</th><th>Domains</th><th>Page</th></tr></thead>
    <tbody>
${rows.join('\n')}
    </tbody>
  </table>
</main>
</body>
</html>
`;
}

export async function build(root, { out = 'dist', only = null, clean = true, now = new Date(), log = console.log } = {}) {
  const store = createStore(root);
  const outDir = path.join(root, out);

  const slugs = only ? [only] : await store.list();
  if (!slugs.length) throw new Error(`No tenants in ${path.join(root, 'tenants')}. Run: npm run new -- <slug>`);

  if (clean && !only) await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  const tenants = [];
  const results = [];
  for (const slug of slugs) {
    const tenant = await store.load(slug);
    tenants.push(tenant);
    const result = await writeTenant(tenant, outDir, { now });
    results.push(result);
    log(`  ${slug.padEnd(24)} ${(result.bytes / 1024).toFixed(1).padStart(6)} KB  ${tenant.config.domains[0] || ''}`);
    for (const warning of result.warnings) log(`    ! ${warning}`);
  }

  const allTenants = only ? await store.loadAll({ strict: false }) : tenants;
  await writeFile(path.join(outDir, 'routes.json'), JSON.stringify(routesFor(allTenants), null, 2) + '\n', 'utf8');
  await writeFile(path.join(outDir, 'Caddyfile'), caddyfile(allTenants), 'utf8');
  await writeFile(path.join(outDir, 'index.html'), directoryPage(results, tenants), 'utf8');

  return { outDir, results };
}
